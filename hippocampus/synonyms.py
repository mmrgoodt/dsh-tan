def pairs():
    """展开成所有互连的对（组内两两相连）"""
    out = []
    seen = set()
    for gname, words in GROUPS.items():
        ws = list(dict.fromkeys(words))
        for i in range(len(ws)):
            for j in range(i + 1, len(ws)):
                a, b = sorted((ws[i].lower(), ws[j].lower()))
                if a == b or (a, b) in seen:
                    continue
                seen.add((a, b))
                out.append((a, b, gname))
    return out


def install(db, weight=7.0):
    """写进 aliases 表。权重 7：比统计推出来的高，比手写的种子低一点"""
    from .aliases import ensure_schema
    ensure_schema(db)
    ps = pairs()
    n = 0
    with db.conn() as con:
        for a, b, _g in ps:
            try:
                con.execute(
                    "INSERT OR REPLACE INTO aliases (a, b, score) VALUES (?,?,?)",
                    (a, b, weight))
                n += 1
            except Exception:
                pass
    return {"pairs": len(ps), "written": n}
